// Build the compact quest-giver schedule index used by the Route, Completion
// Hub, and Quest Lookup. The Affinity data remains the canonical resident source;
// this derived file keeps the always-loaded guide payload small.
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = __dirname;
function loadConst(file, name) {
  const context = {};
  vm.createContext(context);
  const source = fs.readFileSync(path.join(root, file), "utf8");
  vm.runInContext(source.replace(`const ${name}`, name), context, { filename: file });
  return context[name];
}

const world = loadConst("data/world-data.js", "WORLD_DATA");
const affinity = loadConst("data/affinity-data.js", "AFFINITY_DATA");
const completion = loadConst("data/completion-data.js", "COMPLETION_DATA");
const residentsById = new Map(affinity.residents.map(resident => [resident.id, resident]));
const affinityQuestsById = new Map(affinity.quests.map(quest => [quest.id, quest]));
const completionItemsById = new Map(completion.categories.flatMap(category => category.groups.flatMap(group => group.items)).map(item => [item.id, item]));
const QUEST_NAME_CORRECTIONS = Object.freeze({
  "Adventureres in Peril": "Adventurers in Peril"
});
function normalizedSlot(quest, giver) {
  let location = String(quest.location || quest.area || "").trim();
  let time = String(quest.time || "").trim();
  const suffix = location.match(/\s*·\s*(Anytime|Automatic)\.?\s*$/i);
  if (suffix) {
    time = time || suffix[1];
    location = location.slice(0, suffix.index).trim();
  }
  if (!time) time = /^(?:Story Quest|Surprise Quest)$/i.test(giver.name) ? "Automatic" : "Anytime";
  if (!location || /^Automatic$/i.test(location)) location = quest.area;
  return { location, time };
}

const schedules = world.quests.map(quest => {
  const affinityQuest = affinityQuestsById.get(quest.id);
  const resident = affinityQuest && residentsById.get(affinityQuest.giverId);
  return {
    questId: quest.id,
    questName: QUEST_NAME_CORRECTIONS[quest.name] || quest.name,
    area: quest.area,
    requirements: quest.requirements || "",
    details: completionItemsById.get(quest.id)?.details || "",
    givers: resident ? [{
      residentId: resident.id,
      name: resident.name,
      kind: /^(?:Story Quest|Surprise Quest)$/i.test(resident.name) ? "automatic" : "npc",
      locations: [normalizedSlot(affinityQuest, resident)]
    }] : []
  };
});

const missing = schedules.filter(schedule => !schedule.givers.length || schedule.givers.some(giver =>
  !giver.name || !giver.locations.length || giver.locations.some(slot => !slot.location || !slot.time)
));
if (missing.length) {
  throw new Error(`Incomplete quest-giver schedules: ${missing.map(item => item.questName).join(", ")}`);
}

const data = {
  version: 1,
  generated: new Date().toISOString().slice(0, 10),
  source: {
    label: "XCDE Affinity Chart resident schedule ledger",
    url: affinity.sources?.residents?.url || affinity.sources?.[0]?.url || world.source?.checklist?.url || "",
    derivedFrom: "data/affinity-data.js"
  },
  counts: {
    quests: schedules.length,
    givers: schedules.reduce((sum, schedule) => sum + schedule.givers.length, 0),
    scheduleSlots: schedules.reduce((sum, schedule) => sum + schedule.givers.reduce((n, giver) => n + giver.locations.length, 0), 0)
  },
  schedules
};

fs.writeFileSync(
  path.join(root, "data", "quest-schedule-data.js"),
  `// Generated by build-quest-schedule-data.js on ${data.generated}. Do not edit by hand.\nconst QUEST_SCHEDULE_DATA = ${JSON.stringify(data, null, 2)};\n`,
  "utf8"
);
console.log(`Wrote ${data.counts.quests} quest schedules (${data.counts.givers} giver records / ${data.counts.scheduleSlots} active slots).`);
