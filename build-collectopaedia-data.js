// Builds the offline, item-level Collectopaedia tracker from the public XC wiki.
// Refresh deliberately happens at build time only; the guide never fetches while
// the player is using it.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const API = "https://xenoblade.fandom.com/api.php";
const OUT = path.join(__dirname, "data", "collectopaedia-data.js");
const PAGES = [
  ["Colony 9", "Colony 9 Collection"], ["Tephra Cave", "Tephra Cave Collection"],
  ["Bionis' Leg", "Bionis' Leg Collection"], ["Colony 6", "Colony 6 Collection"],
  ["Ether Mine", "Ether Mine Collection"], ["Satorl Marsh", "Satorl Marsh Collection"],
  ["Bionis' Interior", "Bionis' Interior Collection"], ["Makna Forest", "Makna Forest Collection"],
  ["Frontier Village", "Frontier Village Collection"], ["Eryth Sea", "Eryth Sea Collection"],
  ["Alcamoth", "Alcamoth Collection"], ["High Entia Tomb", "High Entia Tomb Collection"],
  ["Valak Mountain", "Valak Mountain Collection"], ["Sword Valley", "Sword Valley Collection"],
  ["Galahad Fortress", "Galahad Fortress Collection"], ["Fallen Arm", "Fallen Arm Collection"],
  ["Mechonis Field", "Mechonis Field Collection"], ["Central Factory", "Central Factory Collection"],
  ["Agniratha", "Agniratha Collection"], ["Prison Island", "Prison Island Collection"], ["Other", "Other Collection"]
];
const SOURCE = page => `https://xenoblade.fandom.com/wiki/${encodeURIComponent(page.replace(/ /g, "_"))}`;
const id = (area, type, name) => `collect-${slug(area)}-${slug(type)}-${slug(name)}-${crypto.createHash("sha1").update(`${area}\u001f${type}\u001f${name}`).digest("hex").slice(0,8)}`;
function slug(value){ return String(value).normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "item"; }
function text(value){ return String(value || "").replace(/\[\[(?:[^\]|]*\|)?([^\]]+)\]\]/g, "$1").replace(/\[\[:[^\]|]+\|([^\]]+)\]\]/g, "$1").replace(/\{\{[^{}]*\}\}/g, "").replace(/<[^>]*>/g, " ").replace(/&nbsp;/g, " ").replace(/''+/g, "").replace(/\s+/g, " ").trim(); }
async function get(page){
  const url = `${API}?action=parse&format=json&page=${encodeURIComponent(page)}&prop=wikitext`;
  let last;
  for(let attempt=0; attempt<3; attempt++) try {
    const res = await fetch(url, {headers:{"user-agent":"XCDE-Collectopaedia-offline-builder/1.0"}});
    if(!res.ok) throw new Error(`HTTP ${res.status}`);
    const body = await res.json(), value = body.parse?.wikitext?.["*"];
    if(!value) throw new Error("no wikitext");
    return value;
  } catch(error) { last = error; await new Promise(resolve=>setTimeout(resolve, 500 * (attempt + 1))); }
  throw new Error(`${page}: ${last.message}`);
}
function cell(raw){
  const clean = raw.replace(/^\s*(?:class|style)="[^"]*"\s*\|\s*/i, "");
  // The type cell is a File link with both a category target and display label.
  // Keep the final visible label rather than treating the category parameter as text.
  const type = clean.match(/\[\[File:[^\]]*\|([^|\]]+)\]\]/i);
  return type ? type[1].trim() : text(clean);
}
function parse(area, page, wiki){
  const table = wiki.match(/\{\|\s*class="xc1 collectopaedia"([\s\S]*?)\n\|\}/i)?.[1];
  if(!table) throw new Error(`${page}: collection table not found`);
  const rows = table.split(/\n\|-\s*/).slice(1).map(row => row.split("\n").filter(line => /^\|/.test(line)).map(line => cell(line.replace(/^\|\s?/, ""))));
  const groups = rows.map(cells => {
    const [type, ...values] = cells;
    const reward = values.pop() || "";
    const items = values.filter(Boolean).map(name => ({id:id(area,type,name),name}));
    return {type, reward, items};
  }).filter(group => group.type && group.items.length);
  const completion = text(wiki.match(/={2,3}\s*(?:\{\{XC[^}]*\}\}\s*)?Completion [Rr]eward\s*={2,3}\s*\n([^\n]+)/)?.[1] || "");
  if(!groups.length || !completion) throw new Error(`${page}: incomplete parse`);
  return {id:slug(area), area, page, source:SOURCE(page), completionReward:completion, groups};
}
async function main(){
  console.log("Downloading Collectopaedia pages...");
  const collections = [];
  for(const [area,page] of PAGES) collections.push(parse(area,page,await get(page)));
  const items = collections.flatMap(collection => collection.groups.flatMap(group => group.items));
  if(collections.length !== PAGES.length || items.length < 300 || new Set(items.map(item => item.id)).size !== items.length) throw new Error(`Unexpected collection coverage: ${collections.length} pages / ${items.length} items`);
  const data = {version:1,generated:new Date().toISOString().slice(0,10),source:{label:"Xenoblade Wiki XC Collectopaedia pages",url:SOURCE("Collectopaedia (XC1)")},collections,counts:{pages:collections.length,items:items.length,rows:collections.reduce((n,c)=>n+c.groups.length,0)}};
  fs.writeFileSync(OUT, `// Generated by build-collectopaedia-data.js on ${data.generated}. Do not edit by hand.\nconst COLLECTOPAEDIA_DATA = ${JSON.stringify(data,null,2)};\nif (typeof window !== "undefined") window.COLLECTOPAEDIA_DATA = COLLECTOPAEDIA_DATA;\n`, "utf8");
  console.log(`Wrote ${data.counts.pages} pages, ${data.counts.rows} rows, ${data.counts.items} items.`);
}
main().catch(error=>{ console.error(error.stack || error); process.exitCode=1; });
